#!/usr/bin/env bash
# Installs the native messaging host that lets the extension call the claude CLI.
# Usage: ./install.sh            (install or update)
#        ./install.sh --uninstall
set -euo pipefail

HOST_NAME="com.clowder_tabs.host"
EXTENSION_ID="eehdejcmldpmhkcefkkhgicgcnapajdl"  # fixed by the "key" in extension/manifest.json
INSTALL_DIR="$HOME/.local/share/clowder"
SRC_DIR="$(cd "$(dirname "$0")" && pwd)"

BROWSER_DIRS=(
  "$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
  "$HOME/Library/Application Support/Google/Chrome Beta/NativeMessagingHosts"
  "$HOME/Library/Application Support/Google/Chrome Canary/NativeMessagingHosts"
  "$HOME/Library/Application Support/Chromium/NativeMessagingHosts"
  "$HOME/Library/Application Support/BraveSoftware/Brave-Browser/NativeMessagingHosts"
)

# Earlier versions installed under the name "Claude Tab Grouper".
remove_legacy() {
  for dir in "${BROWSER_DIRS[@]}"; do rm -f "$dir/com.claude_tab_grouper.host.json"; done
  rm -rf "$HOME/.local/share/claude-tab-grouper"
}

if [[ "${1:-}" == "--uninstall" ]]; then
  for dir in "${BROWSER_DIRS[@]}"; do rm -f "$dir/$HOST_NAME.json"; done
  rm -rf "$INSTALL_DIR"
  remove_legacy
  echo "Removed the native host. Remove the extension from chrome://extensions."
  exit 0
fi

# Chrome starts the host with a minimal environment, so resolve absolute paths
# now instead of relying on PATH or version-manager shims at run time.
CLAUDE_BIN="${CLAUDE_BIN:-$(command -v claude || true)}"
if [[ -z "$CLAUDE_BIN" ]]; then
  echo "Couldn't find the claude CLI on PATH. Install it, or set CLAUDE_BIN=/path/to/claude." >&2
  exit 1
fi
CLAUDE_BIN="$(cd "$(dirname "$CLAUDE_BIN")" && pwd)/$(basename "$CLAUDE_BIN")"

PYTHON_BIN="$(python3 -c 'import sys; print(sys.executable)')"
NODE_DIR="$(dirname "$(node -p 'process.execPath' 2>/dev/null || echo /usr/bin/node)")"

remove_legacy
mkdir -p "$INSTALL_DIR"
cp "$SRC_DIR/host/clowder_host.py" "$INSTALL_DIR/"

cat > "$INSTALL_DIR/run_host.sh" <<EOF
#!/bin/bash
# Generated by install.sh. Re-run it if claude or python moves.
export CLAUDE_BIN="$CLAUDE_BIN"
# claude finds its Keychain login by user name; without these it reports "Not logged in".
export USER="\${USER:-$(id -un)}" LOGNAME="\${LOGNAME:-$(id -un)}"
export PATH="$(dirname "$CLAUDE_BIN"):$NODE_DIR:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin"
exec "$PYTHON_BIN" "$INSTALL_DIR/clowder_host.py" "\$@"
EOF
chmod +x "$INSTALL_DIR/run_host.sh"

MANIFEST=$(cat <<EOF
{
  "name": "$HOST_NAME",
  "description": "Clowder native host",
  "path": "$INSTALL_DIR/run_host.sh",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXTENSION_ID/"]
}
EOF
)

installed=0
for dir in "${BROWSER_DIRS[@]}"; do
  parent="$(dirname "$dir")"
  [[ -d "$parent" ]] || continue
  mkdir -p "$dir"
  printf '%s\n' "$MANIFEST" > "$dir/$HOST_NAME.json"
  echo "Registered host for: $parent"
  installed=1
done
if [[ "$installed" == 0 ]]; then
  echo "No Chrome-family browser profile found under ~/Library/Application Support." >&2
  exit 1
fi

echo
echo "claude:  $CLAUDE_BIN"
echo "python:  $PYTHON_BIN"
echo "host:    $INSTALL_DIR/run_host.sh"
echo
echo "Next: open chrome://extensions, turn on Developer mode, click 'Load unpacked',"
echo "and pick $SRC_DIR/extension (expected ID: $EXTENSION_ID)."
